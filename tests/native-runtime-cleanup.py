"""Exercise the cleanup CLI against generated native-addon build trees."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

HELPER = Path(__file__).resolve().parents[1] / 'nix/cleanup-native-build-metadata.py'
ADDONS = {'argon2': 'argon2.node', 'fuse-native': 'fuse.node', 'leveldown': 'leveldown.node'}
HEADER = '# Do not edit. File was generated by node-gyp\'s "configure" step\n'


class CleanupTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / 'xo'
        for package, addon in ADDONS.items():
            base = self.root / 'node_modules' / package
            (base / 'build/Release/.deps').mkdir(parents=True)
            (base / 'build/Release/obj.target').mkdir()
            (base / 'build/deps/leveldb').mkdir(parents=True)
            for name, value in {
                'package.json': json.dumps({'name': package, 'version': '1.0'}).encode(),
                'index.js': b'module.exports = require("node-gyp-build")(__dirname)',
                'binding.gyp': b'source build specification retained',
                'build/config.gypi': (HEADER + '{"variables":{"python":"/nix/store/build-python"}}').encode(),
                'build/Makefile': b'generated rules',
                'build/binding.Makefile': b'generated rules',
                'build/deps/leveldb/leveldb.target.mk': b'generated rules',
                'build/Release/.deps/addon.node.d': b'generated dependencies',
                'build/Release/obj.target/addon.o': b'object code',
                'build/Release/library.a': b'!<arch>\nstatic archive',
                'build/Release/' + addon: b'\x7fELFcompiled addon bytes',
                'build/Release/runtime.dat': b'runtime data stays intact',
                'build/runtime.json': b'{"runtimeAsset":true}',
            }.items():
                (base / name).write_bytes(value)
        other = self.root / 'node_modules/other/build'
        other.mkdir(parents=True)
        (other / 'config.gypi').write_text('unrelated package metadata stays intact')

    def run_cleanup(self, success=True):
        result = subprocess.run([sys.executable, str(HELPER), str(self.root)], capture_output=True, text=True)
        if success:
            self.assertEqual(result.returncode, 0, result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0)
        return result

    def snapshot(self):
        return {str(path.relative_to(self.root)): path.read_bytes()
                for path in self.root.rglob('*') if path.is_file() and not path.is_symlink()}

    def test_only_generated_metadata_and_intermediates_removed(self):
        before = self.snapshot()
        self.run_cleanup()
        after = self.snapshot()
        for package, addon in ADDONS.items():
            prefix = 'node_modules/' + package + '/'
            for retained in ('package.json', 'index.js', 'binding.gyp', 'build/Release/' + addon,
                             'build/Release/runtime.dat', 'build/runtime.json'):
                self.assertEqual(after[prefix + retained], before[prefix + retained])
            for removed in ('build/config.gypi', 'build/Makefile', 'build/binding.Makefile',
                            'build/deps/leveldb/leveldb.target.mk', 'build/Release/library.a',
                            'build/Release/.deps/addon.node.d', 'build/Release/obj.target/addon.o'):
                self.assertNotIn(prefix + removed, after)
        self.assertEqual(after['node_modules/other/build/config.gypi'], before['node_modules/other/build/config.gypi'])
        self.run_cleanup()
        self.assertEqual(self.snapshot(), after)

    def test_missing_compiled_addon_does_not_partially_clean(self):
        (self.root / 'node_modules/leveldown/build/Release/leveldown.node').unlink()
        before = self.snapshot()
        self.run_cleanup(False)
        self.assertEqual(self.snapshot(), before)

    def test_non_native_addon_fails_before_cleanup(self):
        (self.root / 'node_modules/argon2/build/Release/argon2.node').write_text('not compiled native code')
        before = self.snapshot()
        self.run_cleanup(False)
        self.assertEqual(self.snapshot(), before)

    def test_unrecognized_config_and_package_identity_rejected(self):
        for relative, value in [('build/config.gypi', 'runtime data must not be deleted'),
                                ('package.json', '{"name":"unrelated-package"}')]:
            path = self.root / 'node_modules/argon2' / relative
            original = path.read_bytes()
            path.write_text(value)
            before = self.snapshot()
            self.run_cleanup(False)
            self.assertEqual(self.snapshot(), before)
            path.write_bytes(original)

    def test_symlink_cleanup_targets_and_parents_do_not_escape(self):
        outside = Path(self.temporary.name) / 'outside'
        outside.mkdir()
        (outside / 'sentinel').write_bytes(b'outside untouched')
        for relative in ('build/config.gypi', 'build/Release/obj.target', 'build'):
            path = self.root / 'node_modules/argon2' / relative
            saved = path.with_name(path.name + '.saved')
            path.rename(saved)
            path.symlink_to(outside, target_is_directory=True)
            self.run_cleanup(False)
            self.assertEqual((outside / 'sentinel').read_bytes(), b'outside untouched')
            self.assertTrue((self.root / 'node_modules/leveldown/build/config.gypi').exists())
            path.unlink()
            saved.rename(path)

    def test_unknown_runtime_assets_and_addons_are_retained(self):
        path = self.root / 'node_modules/argon2/build/Release/other.node'
        path.write_bytes(b'\x7fELFadditional runtime addon')
        empty_runtime = path.parent / 'empty-runtime-directory'
        empty_runtime.mkdir()
        self.run_cleanup()
        self.assertTrue(empty_runtime.is_dir())
        self.assertEqual(path.read_bytes(), b'\x7fELFadditional runtime addon')

    def test_installed_build_tool_is_removed_after_addons_are_verified(self):
        tool = self.root / 'node_modules/node-gyp'
        (tool / 'bin').mkdir(parents=True)
        (tool / 'package.json').write_text('{"name":"node-gyp","version":"10.0.0"}')
        (tool / 'bin/node-gyp.js').write_text('build-only compiler launcher')
        scripts = self.root / 'node_modules/.bin'
        scripts.mkdir()
        (scripts / 'node-gyp').symlink_to('../node-gyp/bin/node-gyp.js')
        self.run_cleanup()
        self.assertFalse(tool.exists())
        self.assertFalse((scripts / 'node-gyp').is_symlink())
        self.assertTrue((self.root / 'node_modules/argon2/build/Release/argon2.node').is_file())

    def test_build_tool_identity_is_not_inferred_from_its_directory_name(self):
        tool = self.root / 'node_modules/node-gyp'
        tool.mkdir()
        (tool / 'package.json').write_text('{"name":"runtime-application"}')
        before = self.snapshot()
        self.run_cleanup(False)
        self.assertEqual(self.snapshot(), before)


if __name__ == '__main__':
    unittest.main()
