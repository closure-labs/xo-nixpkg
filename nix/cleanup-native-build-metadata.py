"""Remove generated build-only files from the three locally rebuilt addons."""
import json
from pathlib import Path
import shutil
import sys

ADDONS = {'argon2': 'argon2.node', 'fuse-native': 'fuse.node', 'leveldown': 'leveldown.node'}
CONFIG_HEADER = '# Do not edit. File was generated by node-gyp\'s "configure" step'


def require(condition, message):
    if not condition:
        raise ValueError(message)


def real_directory(path):
    require(not path.is_symlink() and path.is_dir(), 'Expected a real native-addon directory: ' + str(path))


def cleanup(root):
    root = Path(root)
    real_directory(root)
    real_directory(root / 'node_modules')
    removals = []
    generated_directories = set()
    # The npm node-gyp development tool is also copied by the workspace install.
    # All supported native addons were compiled above; it has no runtime role.
    node_gyp = root / 'node_modules/node-gyp'
    if node_gyp.exists() or node_gyp.is_symlink():
        real_directory(node_gyp)
        manifest = node_gyp / 'package.json'
        require(not manifest.is_symlink() and manifest.is_file()
                and json.loads(manifest.read_text()).get('name') == 'node-gyp',
                'Unexpected installed native build-tool identity')
        require(not any(node_gyp.rglob('*.node')), 'Native runtime binary inside build-only tool')
        removals.append(node_gyp)
        launcher = root / 'node_modules/.bin/node-gyp'
        if launcher.exists() or launcher.is_symlink():
            require(launcher.is_symlink() and launcher.resolve() == (node_gyp / 'bin/node-gyp.js').resolve(),
                    'Unexpected node-gyp launcher')
            removals.append(launcher)
    # Validate every package before mutation; absent binaries or unfamiliar
    # metadata must never produce a partially cleaned successful installation.
    for package, addon in ADDONS.items():
        base = root / 'node_modules' / package
        real_directory(base)
        manifest = base / 'package.json'
        require(not manifest.is_symlink() and manifest.is_file()
                and json.loads(manifest.read_text()).get('name') == package,
                'Native-addon package identity differs: ' + package)
        build, release = base / 'build', base / 'build/Release'
        real_directory(build)
        real_directory(release)
        binary = release / addon
        require(not binary.is_symlink() and binary.is_file(), 'Missing compiled native addon: ' + str(binary))
        with binary.open('rb') as stream:
            require(stream.read(4) == b'\x7fELF', 'Expected compiled ELF native addon: ' + str(binary))
        targets = [build / 'config.gypi', build / 'Makefile', build / 'binding.Makefile',
                   *build.rglob('*.target.mk'), release / '.deps', release / 'obj.target', *release.glob('*.a')]
        targets = [path for path in targets if path.exists() or path.is_symlink()]
        if targets:
            config = build / 'config.gypi'
            require(not config.is_symlink() and config.is_file()
                    and config.read_text().startswith(CONFIG_HEADER + "\n"),
                    'Cannot identify generated node-gyp configuration: ' + str(config))
        for target in targets:
            require(not target.is_symlink(), 'Refusing symlinked build metadata: ' + str(target))
            for parent in target.parents:
                if parent == build:
                    break
                real_directory(parent)
            if target.is_dir():
                require(target in (release / '.deps', release / 'obj.target')
                        and not any(path.is_symlink() for path in target.rglob('*')),
                        'Unexpected native build metadata directory: ' + str(target))
            else:
                require(target.is_file(), 'Unexpected native build metadata file: ' + str(target))
                if target.suffix == '.a':
                    with target.open('rb') as stream:
                        require(stream.read(8) == b'!<arch>\n', 'Unrecognized static build archive: ' + str(target))
        removals.extend(targets)
        for target in targets:
            if target.name.endswith('.target.mk'):
                for parent in target.parents:
                    if parent == build:
                        break
                    generated_directories.add(parent)
    for target in removals:
        if target.is_dir() and not target.is_symlink():
            shutil.rmtree(target)
        else:
            target.unlink()
    # Empty generated dependency directories may disappear; runtime content
    # with an unfamiliar name is deliberately retained, including other .node.
    for path in sorted(generated_directories, key=lambda path: len(path.parts), reverse=True):
        if path.is_dir() and not path.is_symlink() and not any(path.iterdir()):
            path.rmdir()
    print('Removed ' + str(len(removals)) + ' generated native-addon metadata/intermediate paths')


if __name__ == '__main__':
    require(len(sys.argv) == 2, 'Usage: cleanup-native-build-metadata.py INSTALLED_XO_ROOT')
    cleanup(sys.argv[1])
